#!/usr/bin/env bash
# Build all local deliverables and assemble the static GitHub Pages site.
# Run after starting in the project root. plasTeX/leanblueprint must be on PATH.
set -euo pipefail
cd "$(dirname "$0")/.."
python3 blueprint/check_blueprint.py --structure-only
mkdir -p blueprint/site
(cd blueprint/src && latexmk -r latexmkrc print.tex)
dot -Tsvg blueprint/dependency_graph.dot -o blueprint/dependency_graph.svg
cp blueprint/index.html blueprint/site/index.html
cp blueprint/src/print.pdf blueprint/site/blueprint.pdf
cp blueprint/dependency_graph.svg blueprint/site/dependency_graph.svg
(cd blueprint/src && plastex --config plastex.cfg web.tex)
cp -R blueprint/web blueprint/site/web
# The index is deliberately self-contained: the web directory's links and
# static resource paths work at both /blueprint/ and /cubic_twostage/blueprint/.
# This directory is regenerated by CI, not a source documentation directory.
